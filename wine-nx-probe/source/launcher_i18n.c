static int compare( const void *a, const void *b )
{
    return strcmp( ((const struct translation *)a)->en, ((const struct translation *)b)->en );
}

void launcher_set_language( const char *code )
{
    language = code && !strcmp( code, "en" ) ? LAUNCHER_ENGLISH : LAUNCHER_RUSSIAN;
    if (!sorted)
    {
        qsort( messages, sizeof(messages) / sizeof(messages[0]), sizeof(messages[0]), compare );
        for (size_t i = 1; i < sizeof(messages) / sizeof(messages[0]); i++)
            assert( strcmp( messages[i - 1].en, messages[i].en ) < 0 );
        sorted = 1;
    }
}

const char *launcher_language_code(void) { return language == LAUNCHER_ENGLISH ? "en" : "ru"; }

const char *launcher_tr( const char *text )
{
    struct translation key = { text, NULL }, *found;

    if (!text || language == LAUNCHER_ENGLISH) return text;
    if (!sorted) launcher_set_language( "ru" );
    found = bsearch( &key, messages, sizeof(messages) / sizeof(messages[0]), sizeof(messages[0]), compare );
    return found ? found->ru : text;
}

int launcher_snprintf( char *out, size_t size, const char *format, ... )
{
    int result;
    va_list args;

    va_start( args, format );
    result = vsnprintf( out, size, launcher_tr( format ), args );
    va_end( args );
    return result;
}
